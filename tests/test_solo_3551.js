assert.equal(Accounting.getItemBaseStock('b'),6);
assert.equal(Accounting.getItemBaseStock('kit'),6);
kit.bundleComponents=[{itemId:'a',quantity:1},{itemId:'b',quantity:1}];
assert.equal(Accounting.getItemBaseStock('a'),14,'historic BOM frozen on sale');
kit.bundleComponents=[{itemId:'a',quantity:2},{itemId:'b',quantity:1}];
state.invoices.push({id:'ret1',type:'sale_return',warehouseId:'wh_main',rows:[{itemId:'kit',qty:1,unitFactor:1,bomComponents:[{itemId:'a',quantity:2},{itemId:'b',quantity:1}]}]});
assert.equal(Accounting.getItemBaseStock('a'),16);
assert.equal(Accounting.getItemBaseStock('b'),7);
assert.equal(Accounting.getItemBaseStock('kit'),7);
assert(main.includes('item.isBundle ? 0 : stock *'),'Kit must not double-count component value in inventory');
assert(main.includes("row.priceManuallySet=true"),'Price overrides must remain manual');
assert(!main.includes("onclick=\"FieldCash.openTransfer('fromAgent','${AppEscape.text(cashScope)}')\""),'Cash transfer icon removed from reports');
// Solo has no representative app, no agent catalogs and no sync.
assert(!main.includes('manager-agent-hub.js'));
