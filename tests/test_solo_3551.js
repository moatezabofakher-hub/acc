'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const main=fs.readFileSync('app/src/main/assets/www/index.html','utf8');
const item=(id,base,cost,whole,center)=>({id,name:id,category:'م',currency:'USD',openingStockBase:base,units:[{name:'وحدة',factor:1,costPrice:cost,salePrice:whole,centerPrice:center,wholesalePrice:whole}]});
const a=item('a',20,2,3,4),b=item('b',9,5,6,8);
const kit=item('kit',0,9,12,16);
kit.isBundle=true;kit.bundleComponents=[{itemId:'a',quantity:2},{itemId:'b',quantity:1}];kit.bundlePricing={mode:'component_sum',markup:0};
const cust={id:'c',name:'الزبون الأول',type:'customer',priceTier:'center',openingSyp:0,openingUsd:0};
const state={items:[a,b,kit],accounts:[cust],invoices:[],transfers:[],categories:['م'],warehouses:[{id:'wh_main',name:'main'}],settings:{exchangeRate:15000,companyName:'Test',selectedWarehouseId:'wh_main'},fieldSync:{companyId:'company_abcde12345',agents:[],imported:[],events:[],cashTransfers:[]}};
const beginning=main.indexOf('itemCostPrice(item,unit) {');
const ending=main.indexOf('// Double-Entry Account Statement',beginning);
assert(beginning>0&&ending>beginning,'Item cost, tier pricing and stock methods should exist');
const snippet=main.slice(beginning,ending).trim();
const Accounting=new Function('State',`return ({convert(v){return Number(v)},roundDerivedItemPrice(v){return Math.round(v*10000)/10000},${snippet}});`)(state);
assert.equal(Accounting.itemCostPrice(kit,kit.units[0]),9);
assert.equal(Accounting.itemSalePrice(kit,kit.units[0],''),12);
assert.equal(Accounting.itemSalePrice(kit,kit.units[0],'c'),16);
assert.equal(Accounting.itemSalePrice(a,a.units[0],'c'),4);
assert.equal(Accounting.getItemBaseStock('kit'),9);
state.invoices.push({id:'inv1',type:'sale',warehouseId:'wh_main',rows:[{itemId:'kit',qty:3,unitFactor:1,bomComponents:[{itemId:'a',quantity:2},{itemId:'b',quantity:1}]}]});
